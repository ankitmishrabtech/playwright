let arr = [1, 2, 3, 4];
console.log(arr);

// Add to end
arr.push(5);
console.log(arr);

// Remove from END
arr.pop();
console.log(arr)

// Multiple push
arr.push(6, 7);
console.log(arr);

// Add at the starting

arr.unshift(100);
console.log(arr);

// Remove from Starting

arr.shift();
console.log(arr);

// -----------------------------------
console.log(arr);
arr.unshift(0);
console.log(arr);

arr.shift();
console.log(arr);











